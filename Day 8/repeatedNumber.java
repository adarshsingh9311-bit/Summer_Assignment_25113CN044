public class repeatedNumber {
    public static void main(String[] args) {
        int m = 5;
     

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= i; j++) {
                System.out.print(i+"");
                 
               
            }
           
           
            System.out.println(); // Move to the next line
        }
    

            
            // Move to the next character
            System.out.println(); // Move to the next line
        
    }
}

